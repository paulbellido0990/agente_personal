import {test,expect} from '@playwright/test'
const API='http://127.0.0.1:3012/api'
test.beforeEach(async({request})=>{
 for(const task of (await(await request.get(API+'/tasks')).json()).data)await request.delete(API+'/tasks/'+task.id)
})
async function ready(page){
 await page.goto('/')
 await page.evaluate(async()=>{await navigator.serviceWorker.ready})
 await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true)
 await expect(page.getByText('Conectado al backend local',{exact:true})).toBeVisible()
}
test('manifest, iconos, SW e instalabilidad Chromium sin recursos externos',async({page,request})=>{
 const external=[];page.on('request',req=>{if(!new URL(req.url()).hostname.match(/^(127\.0\.0\.1|localhost)$/))external.push(req.url())})
 await ready(page)
 await expect(page.getByRole('button',{name:'Actualizar ALIRA',exact:true})).toHaveCount(0)
 const manifest=await(await request.get('/manifest.webmanifest')).json()
 expect(manifest.name).toBe('ALIRA');expect(manifest.display).toBe('standalone')
 for(const size of [192,512]){
  const icon=manifest.icons.find(i=>i.sizes===size+'x'+size)
  expect(icon).toBeTruthy()
  const response=await request.get(icon.src);const bytes=await response.body()
  expect(bytes.readUInt32BE(16)).toBe(size);expect(bytes.readUInt32BE(20)).toBe(size)
 }
 expect(manifest.icons.some(i=>i.purpose==='maskable')).toBe(true)
 const cdp=await page.context().newCDPSession(page)
 const result=await cdp.send('Page.getInstallabilityErrors')
 expect(result.installabilityErrors).toEqual([])
 expect(external).toEqual([])
 await expect(page.getByRole('button',{name:'Asistente IA',exact:true})).toHaveCount(0)
 expect((await request.get(API+'/assistant/status')).status()).toBe(404)
})
test('offline: abre interfaz, no guarda ni cachea API; reconecta sin duplicar tareas',async({page,context,request})=>{
 await request.post(API+'/tasks',{data:{titulo:'Conservar tarea PWA',descripcion:'Dato privado',categoria:'Personal',prioridad:'media',estado:'pendiente',fechaLimite:null}})
 await ready(page)
 await expect(page.locator('.task-panel')).toContainText('Conservar tarea PWA')
 await context.setOffline(true)
 await expect(page.getByRole('button',{name:'Nueva tarea',exact:true})).toBeDisabled()
 await expect(page.getByText('Sin conexión con el backend.',{exact:false})).toBeVisible()
 await page.reload()
 await expect(page.getByRole('heading',{name:/Un día más cerca/})).toBeVisible()
 await expect(page.getByText('Resumen no disponible hasta conectar con el servidor.',{exact:true})).toBeVisible()
 const entries=await page.evaluate(async()=>{const all=[];for(const name of await caches.keys())for(const req of await(await caches.open(name)).keys())all.push(req.url);return all})
 expect(entries.every(url=>!url.includes('/api/'))).toBe(true)
 await page.getByRole('button',{name:'Estadísticas',exact:true}).click()
 await expect(page.getByText('Estadísticas sin conexión:',{exact:false})).toBeVisible()
 await expect(page.getByRole('button',{name:'Exportar CSV',exact:true})).toHaveCount(0)
 await context.setOffline(false)
 await expect(page.getByText('Conectado al backend local',{exact:true})).toBeVisible({timeout:20000})
 await page.getByRole('button',{name:'Mis tareas',exact:true}).first().click()
 await expect(page.locator('.task-panel')).toContainText('Conservar tarea PWA')
 expect((await(await request.get(API+'/tasks')).json()).data).toHaveLength(1)
})
test('API caída con navegador online bloquea acciones y recupera los datos',async({page})=>{
 await ready(page)
 await page.route('**/api/tasks',r=>r.abort())
 await page.getByRole('button',{name:'Actualizar listado',exact:true}).click()
 await expect(page.getByText('No se pudo conectar con el backend',{exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Nueva tarea',exact:true})).toBeDisabled()
 await page.unroute('**/api/tasks')
 await expect(page.getByText('Conectado al backend local',{exact:true})).toBeVisible({timeout:20000})
})
