test('instalación: evento controlado y modo standalone sin botones repetidos',async({page})=>{
 await ready(page)
 await expect(page.getByRole('button',{name:'Instalar ALIRA',exact:true})).toHaveCount(0)
 // Simula únicamente el evento de UI; no prueba una instalación física.
 await page.evaluate(()=>{const event=new Event('beforeinstallprompt');event.prompt=async()=>{};event.userChoice=Promise.resolve({outcome:'dismissed'});window.dispatchEvent(event)})
 await expect(page.getByRole('button',{name:'Instalar ALIRA',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Instalar ALIRA',exact:true}).click()
 await expect(page.getByRole('button',{name:'Instalar ALIRA',exact:true})).toHaveCount(0)
 await page.evaluate(()=>window.dispatchEvent(new Event('appinstalled')))
 await expect(page.getByText('Aplicación instalada',{exact:true})).toBeVisible()
})
