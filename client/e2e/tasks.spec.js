import { test, expect } from '@playwright/test'
const API = 'http://127.0.0.1:3011/api'
test.beforeEach(async ({ request }) => {
  const response = await request.get(API + '/tasks')
  for (const task of (await response.json()).data) await request.delete(API + '/tasks/' + task.id)
})
test('React crea, edita, cambia estado, filtra, recarga y elimina con confirmación', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByText('Conectado al backend local', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Nueva tarea', exact: true }).click()
  await page.getByLabel('Título *', { exact: true }).fill('Informe desde React')
  await page.getByLabel('Descripción', { exact: true }).fill('Revisar fuentes académicas')
  await page.getByLabel('Categoría', { exact: true }).fill('Universidad')
  await page.getByLabel('Fecha límite', { exact: true }).fill('2026-10-16')
  await page.getByRole('button', { name: 'Crear tarea', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('Informe desde React', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('alira-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Editar Informe desde React', exact: true }).click()
  await page.getByLabel('Título *', { exact: true }).fill('Informe editado')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Mis tareas', exact: true }).first().click()
  await page.getByRole('combobox', { name: 'Estado de Informe editado', exact: true }).selectOption('completada')
  await expect(page.locator('.progress-ring')).toHaveAttribute('aria-valuenow', '100')
  await page.getByRole('searchbox').fill('fuentes académicas')
  await expect(page.getByText('Informe editado', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Filtrar por estado', exact: true }).selectOption('pendiente')
  await expect(page.getByText('No hay tareas en esta vista', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Filtrar por estado', exact: true }).selectOption('completada')
  await page.getByRole('combobox', { name: 'Ordenar tareas por', exact: true }).selectOption('prioridad')
  await expect(page.getByText('Informe editado', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Mis tareas', exact: true }).first().click()
  await expect(page.getByText('Informe editado', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar Informe editado', exact: true }).click()
  await page.getByRole('button', { name: 'Conservar tarea', exact: true }).click()
  await expect(page.getByText('Informe editado', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar Informe editado', exact: true }).click()
  await page.getByRole('button', { name: 'Eliminar tarea', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(page.getByText('Tu próximo logro empieza aquí', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
test('importa explícitamente, reintenta sin duplicar y conserva localStorage', async ({ page, request }) => {
  const legacy = [{ id: 'local-browser', titulo: 'Tarea local previa', descripcion: '', categoria: 'Estudio', prioridad: 'media', estado: 'pendiente', fechaLimite: null, createdAt: '2026-10-14T15:00:00.000Z', updatedAt: '2026-10-14T15:00:00.000Z' }]
  await page.addInitScript(data => { if (!localStorage.getItem('alira.tasks.v1')) localStorage.setItem('alira.tasks.v1', JSON.stringify(data)) }, legacy)
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Importar tareas locales', exact: true })).toBeEnabled()
  expect((await (await request.get(API + '/tasks')).json()).data).toHaveLength(0)
  for (let i = 0; i < 2; i++) {
    await page.getByRole('button', { name: 'Importar tareas locales', exact: true }).click()
    await page.getByRole('button', { name: 'Confirmar importación', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
  }
  expect((await (await request.get(API + '/tasks')).json()).data).toHaveLength(1)
  expect(JSON.parse(await page.evaluate(() => localStorage.getItem('alira.tasks.v1')))).toEqual(legacy)
  await page.getByRole('button', { name: 'Explorar demo', exact: true }).click()
  await expect(page.getByText('Preparar informe de inteligencia artificial', { exact: true })).toBeVisible()
  expect((await (await request.get(API + '/tasks')).json()).data).toHaveLength(1)
  await page.getByRole('button', { name: 'Volver a mis tareas', exact: true }).click()
  await expect(page.getByText('Tarea local previa', { exact: true })).toBeVisible()
})
test('error de conexión conserva el listado y no anuncia un guardado falso', async ({ page, request }) => {
  await request.post(API + '/tasks', { data: { titulo: 'Conservar tarea visible', descripcion: '', categoria: 'Personal', prioridad: 'media', estado: 'pendiente', fechaLimite: null } })
  await page.goto('/')
  await expect(page.getByText('Conservar tarea visible', { exact: true })).toBeVisible()
  await page.route('**/api/tasks/**', route => route.abort())
  await page.getByRole('button', { name: 'Editar Conservar tarea visible', exact: true }).click()
  await page.getByLabel('Título *', { exact: true }).fill('No confirmado')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('No se confirmó el guardado')
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.getByText('Conservar tarea visible', { exact: true })).toBeVisible()
  await page.route('**/api/tasks', route => route.abort())
  await page.getByRole('button', { name: 'Actualizar listado', exact: true }).click()
  await expect(page.getByText('No se pudo conectar con el backend', { exact: true })).toBeVisible()
  await expect(page.getByText('Conservar tarea visible', { exact: true })).toBeVisible()
})
test('móvil 360 px: navegación, formulario por teclado y sin desbordamiento', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('/')
  await expect(page.getByText('Conectado al backend local', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Abrir menú', exact: true }).click()
  await expect(page.locator('#navigation').getByRole('button', { name: 'Cerrar menú', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Nueva tarea', exact: true }).click()
  await expect(page.getByLabel('Título *', { exact: true })).toBeFocused()
  await page.getByLabel('Título *', { exact: true }).fill('Tarea móvil')
  await page.getByRole('button', { name: 'Crear tarea', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('Tarea móvil', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Nueva tarea', exact: true })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('alira-mobile.png'), fullPage: true })
})

