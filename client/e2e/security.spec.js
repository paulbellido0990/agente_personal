import {test,expect} from './fixtures'
test('inicio de sesión real, errores genéricos, cookie HttpOnly y cierre sin datos privados',async({page,context},testInfo)=>{
 await context.clearCookies()
 await page.goto('/')
 await expect(page.getByRole('button',{name:'Iniciar sesión',exact:true})).toBeVisible()
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:testInfo.outputPath('login-mobile.png'),fullPage:true})
 await page.setViewportSize({width:1280,height:900})
 await page.getByLabel('Usuario',{exact:true}).fill('browser-owner')
 await page.getByLabel('Contraseña',{exact:true}).fill('incorrecta')
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
 await expect(page.getByText('Usuario o contraseña incorrectos.',{exact:true})).toBeVisible()
 await page.getByLabel('Contraseña',{exact:true}).fill('browser-private-password')
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
 await expect(page.getByRole('button',{name:'Nueva tarea',exact:true})).toBeEnabled()
 expect(await page.evaluate(()=>document.cookie.includes('alira.sid'))).toBe(false)
 await page.getByRole('button',{name:'Configuración',exact:true}).click()
 await page.getByRole('button',{name:'Cerrar sesión',exact:true}).click()
 await expect(page.getByRole('button',{name:'Iniciar sesión',exact:true})).toBeVisible()
 await expect(page.locator('.task-panel')).toHaveCount(0)
 expect((await page.request.get('http://127.0.0.1:3011/api/tasks')).status()).toBe(401)
 await page.reload()
 await expect(page.getByRole('button',{name:'Iniciar sesión',exact:true})).toBeVisible()
})
test('dos dispositivos: actualización visible y formulario antiguo no sobrescribe cambios',async({page,browser,request})=>{
 const created=await request.post('http://127.0.0.1:3011/api/tasks',{data:{titulo:'Conflicto entre dispositivos',descripcion:'Original',categoria:'Estudio',prioridad:'media',estado:'pendiente',fechaLimite:null}})
 const task=(await created.json()).data
 await page.goto('/')
 await page.getByRole('button',{name:'Editar Conflicto entre dispositivos',exact:true}).click()
 await page.getByLabel('Título *',{exact:true}).fill('Edición antigua')
 const second=await browser.newContext()
 try{
  const r=await second.request.post('http://127.0.0.1:3011/api/auth/login',{headers:{'X-Alira-Request':'1'},data:{username:'browser-owner',password:'browser-private-password'}})
  const csrf=(await r.json()).data.csrfToken
  const changed=await second.request.put('http://127.0.0.1:3011/api/tasks/'+task.id,{headers:{'X-CSRF-Token':csrf,'If-Match':'"'+task.version+'"'},data:{titulo:'Cambio desde el segundo dispositivo',descripcion:'Original',categoria:'Estudio',prioridad:'alta',estado:'pendiente',fechaLimite:null}})
  expect(changed.status()).toBe(200)
  await page.getByRole('button',{name:'Guardar cambios',exact:true}).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toBeVisible()
  await page.getByRole('button',{name:'Cancelar',exact:true}).click()
  await page.getByRole('button',{name:'Actualizar listado',exact:true}).click()
  await expect(page.locator('.task-panel')).toContainText('Cambio desde el segundo dispositivo')
  const otherPage=await second.newPage();await otherPage.goto('http://127.0.0.1:5174')
  await expect(otherPage.locator('.task-panel')).toContainText('Cambio desde el segundo dispositivo')
 }finally{await second.close()}
})
test('respaldo exige contraseña y descarga SQLite privado',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Configuración',exact:true}).click()
 await page.getByLabel('Contraseña para autorizar el respaldo',{exact:true}).fill('incorrecta')
 await page.getByRole('button',{name:'Descargar respaldo privado',exact:true}).click()
 await expect(page.getByText('No se pudo verificar la contraseña actual.',{exact:true})).toBeVisible()
 await page.getByLabel('Contraseña para autorizar el respaldo',{exact:true}).fill('browser-private-password')
 const pending=page.waitForEvent('download')
 await page.getByRole('button',{name:'Descargar respaldo privado',exact:true}).click()
 const download=await pending
 expect(download.suggestedFilename()).toMatch(/ALIRA-respaldo.*\.db$/)
 await expect(page.getByText('Respaldo descargado.',{exact:false})).toBeVisible()
})
