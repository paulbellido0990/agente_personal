 await dialog.getByRole('button',{name:'Guardar asignatura',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await module.getByRole('button',{name:'Horario',exact:true}).click()
 for(const start of ['10:00','11:00']){
  await module.getByRole('button',{name:'Añadir sesión',exact:true}).click()
  await dialog.getByLabel('Hora de inicio *').fill(start)
  await dialog.getByLabel('Hora de finalización *').fill('12:00')
  await dialog.getByLabel('Día de la semana *').selectOption(String(((new Date(localDay()+'T12:00:00Z').getUTCDay()+6)%7)+1))
  await dialog.getByRole('button',{name:'Guardar sesión de clase',exact:true}).click()
  await expect(dialog).toHaveCount(0)
 }
 await expect(module.getByText('Superposición con otra sesión. Revisa los horarios.').first()).toBeVisible()
 for(const width of [360,390,768,1024,1440]){
  await page.setViewportSize({width,height:900})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 }
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:info.outputPath('academic-week.png'),fullPage:true})
 await module.getByRole('button',{name:'Evaluaciones',exact:true}).click()
 await module.getByRole('button',{name:'Crear evaluación',exact:true}).click()
