 await dialog.getByLabel('Número de laboratorio').fill('1')
 await dialog.getByLabel('Fecha de realización').fill(localDay())
 await dialog.getByLabel('Fecha límite',{exact:true}).fill(localDay())
 await dialog.getByRole('button',{name:'Crear tarea',exact:true}).click()
