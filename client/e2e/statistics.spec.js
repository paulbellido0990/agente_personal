import {test,expect} from './fixtures'
import {readFile} from 'node:fs/promises'
import {localDay,addDays} from '../../shared/tasks.js'
const API='http://127.0.0.1:3011/api',today=localDay()
const input={titulo:'Actividad para estadísticas',descripcion:'Dato de prueba aislado',categoria:'Estudio',prioridad:'alta',estado:'pendiente',fechaLimite:today}
test.beforeEach(async({request})=>{
  for(const task of (await(await request.get(API+'/tasks')).json()).data)await request.delete(API+'/tasks/'+task.id)
})
test('estadísticas reales, gráficos, filtros, CSV y PDF A4',async({page,request},testInfo)=>{
  for(const extra of [{titulo:'Pendiente nueva'},{titulo:'En curso nueva',estado:'en_progreso',prioridad:'media',categoria:'Personal'},{titulo:'Completada nueva',estado:'completada',prioridad:'baja'}])await request.post(API+'/tasks',{data:{...input,...extra}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button',{name:'Estadísticas',exact:true}).click()
  const section=page.locator('.statistics-page')
  await expect(section.getByText('Datos de SQLite · fechas locales de America/Lima',{exact:true})).toBeVisible()
  await expect(section.locator('.statistic-tile').filter({hasText:'Total de tareas'}).locator('strong')).toHaveText('3')
  await expect(section.locator('.statistic-tile').filter({hasText:'Porcentaje completado'}).locator('strong')).toHaveText('33.3%')
  await expect(section.getByRole('heading',{name:'Actividad semanal',exact:true})).toBeVisible()
  await section.getByText('Ver datos de distribución por estado',{exact:true}).click()
  await expect(section.locator('.chart-data[open]').getByText('Pendientes',{exact:true})).toBeVisible()
  for(const format of ['CSV','PDF A4']){
    const pending=page.waitForEvent('download')
    await section.getByRole('button',{name:'Exportar '+format,exact:true}).click()
    const download=await pending
    const path=testInfo.outputPath(format==='CSV'?'reporte.csv':'reporte.pdf')
    await download.saveAs(path);const bytes=await readFile(path)
    if(format==='CSV'){expect(bytes.toString()).toContain('ALIRA');expect(bytes.toString()).toContain(today)}
    else{expect(bytes.subarray(0,4).toString()).toBe('%PDF');expect(bytes.toString('latin1')).toMatch(/MediaBox \[0 0 595\.28 841\.89\]/)}
  }
  await section.getByRole('combobox',{name:'Periodo estadístico',exact:true}).selectOption('30')
  await expect(section.getByRole('button',{name:'Exportar CSV',exact:true})).toBeVisible()
  await section.getByRole('combobox',{name:'Periodo estadístico',exact:true}).selectOption('month')
  await expect(section.getByRole('button',{name:'Exportar CSV',exact:true})).toBeVisible()
  await section.getByRole('combobox',{name:'Periodo estadístico',exact:true}).selectOption('custom')
  await section.getByLabel('Desde',{exact:true}).fill(addDays(today,-1))
  await section.getByLabel('Hasta',{exact:true}).fill(today)
  await section.getByRole('button',{name:'Aplicar periodo',exact:true}).click()
  await expect(section.getByText(addDays(today,-1)+' al '+today,{exact:true})).toBeVisible()
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:testInfo.outputPath('statistics-desktop.png'),fullPage:true})
  expect(errors).toEqual([])
})
test('metas: crear, editar, progreso, desactivar y recargar',async({page,request})=>{
  await request.post(API+'/tasks',{data:{...input,estado:'completada'}})
  // Los eventos de tareas eliminadas se conservan entre casos de este servidor temporal.
  const completed=(await(await request.get(API+'/statistics')).json()).data.summary.completed
  await page.goto('/')
  await page.getByRole('button',{name:'Objetivos',exact:true}).click()
  await page.getByRole('button',{name:'Nueva meta',exact:true}).click()
  await page.getByLabel('Nombre de la meta',{exact:true}).fill('Meta de navegador')
  await page.getByLabel('Cantidad objetivo',{exact:true}).fill(String(completed*2))
  await page.getByRole('button',{name:'Crear meta',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  let card=page.locator('.goal-card').filter({has:page.getByRole('heading',{name:'Meta de navegador',exact:true})})
  await expect(card.getByRole('progressbar')).toHaveAttribute('aria-valuenow','50')
  await card.getByRole('button',{name:'Editar Meta de navegador',exact:true}).click()
  await page.getByLabel('Cantidad objetivo',{exact:true}).fill(String(completed))
  await page.getByRole('button',{name:'Guardar meta',exact:true}).click()
  await expect(card.getByRole('progressbar')).toHaveAttribute('aria-valuenow','100')
  await card.getByRole('button',{name:'Desactivar Meta de navegador',exact:true}).click()
  await expect(card.getByText('Desactivada',{exact:true})).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:'Objetivos',exact:true}).click()
  card=page.locator('.goal-card').filter({has:page.getByRole('heading',{name:'Meta de navegador',exact:true})})
  await expect(card.getByText('Desactivada',{exact:true})).toBeVisible()
  await expect(card.getByRole('progressbar')).toHaveAttribute('aria-valuenow','100')
})
test('demo excluida y reportes desactualizados o desconectados no se exportan',async({page,request})=>{
  await page.goto('/')
  await expect(page.getByRole('button',{name:'Explorar demo',exact:true})).toBeEnabled()
  await page.getByRole('button',{name:'Explorar demo',exact:true}).click()
  await page.getByRole('button',{name:'Estadísticas',exact:true}).click()
  await expect(page.getByText(/La demo está excluida de las estadísticas/)).toBeVisible()
  await expect(page.getByRole('button',{name:'Exportar CSV',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Volver a mis tareas',exact:true}).click()
  await expect(page.getByRole('button',{name:'Exportar CSV',exact:true})).toBeVisible()
  await request.post(API+'/tasks',{data:{...input,titulo:'Cambio externo posterior'}})
  await page.getByRole('button',{name:'Exportar CSV',exact:true}).click()
  await expect(page.getByRole('alert').filter({hasText:'Los datos cambiaron'})).toBeVisible()
  await page.route('**/api/statistics?*',route=>route.abort())
  await page.getByRole('button',{name:'Actualizar reporte',exact:true}).click()
  await expect(page.getByRole('alert').filter({hasText:'No se exportarán datos desactualizados'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Exportar CSV',exact:true})).toHaveCount(0)
})
